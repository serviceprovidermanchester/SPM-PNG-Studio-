export const EXT = {
  PNG: 'png',
  JPG: 'jpg',
  WEBP: 'webp',
  GIF: 'gif',
  BMP: 'bmp',
  ICO: 'ico',
  SVG: 'svg',
  PDF: 'pdf',
  BASE64: 'txt'
};

export const MIME = {
  PNG: 'image/png',
  JPG: 'image/jpeg',
  WEBP: 'image/webp',
  GIF: 'image/gif',
  BMP: 'image/bmp',
  ICO: 'image/x-icon',
  SVG: 'image/svg+xml',
  PDF: 'application/pdf',
  BASE64: 'text/plain'
};

export function decodeImage(file) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    const url = URL.createObjectURL(file);
    img.onload = () => {
      URL.revokeObjectURL(url);
      resolve(img);
    };
    img.onerror = () => {
      URL.revokeObjectURL(url);
      reject(new Error(`Failed to decode image file ${file.name}`));
    };
    img.src = url;
  });
}

export function calculateDimensions(imgWidth, imgHeight, scaleOrCustom, customWidth) {
  let w, h;
  if (scaleOrCustom === 'custom') {
    const targetW = Math.max(1, Math.min(16000, Number(customWidth) || imgWidth));
    const ratio = imgHeight / imgWidth;
    w = targetW;
    h = Math.round(targetW * ratio);
  } else {
    const scale = Number(scaleOrCustom) || 1;
    w = Math.round(imgWidth * scale);
    h = Math.round(imgHeight * scale);
  }

  // Safety cap at 36 Megapixels to prevent browser OOM crashes
  const totalPixels = w * h;
  if (totalPixels > 36000000) {
    const downscale = Math.sqrt(36000000 / totalPixels);
    w = Math.floor(w * downscale);
    h = Math.floor(h * downscale);
  }

  return { width: Math.max(1, w), height: Math.max(1, h) };
}

export function renderToCanvas(img, targetFormat, dimensions) {
  const canvas = document.createElement('canvas');
  canvas.width = dimensions.width;
  canvas.height = dimensions.height;
  const ctx = canvas.getContext('2d');

  // Background flattening logic:
  // JPG, BMP, PDF do not support transparency; flatten onto solid white
  if (['JPG', 'BMP', 'PDF'].includes(targetFormat)) {
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
  }

  ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
  return canvas;
}

export async function canvasToBlob(canvas, mimeType, quality) {
  return new Promise((resolve, reject) => {
    canvas.toBlob(
      (blob) => {
        if (blob) resolve(blob);
        else reject(new Error(`Failed to encode canvas to ${mimeType}`));
      },
      mimeType,
      quality
    );
  });
}

export async function canvasToSvgBlob(canvas) {
  const png = await canvasToBlob(canvas, 'image/png');
  const bytes = new Uint8Array(await png.arrayBuffer());
  let b = '';
  for (let i = 0; i < bytes.length; i += 32768) {
    b += String.fromCharCode(...bytes.subarray(i, i + 32768));
  }
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${canvas.width}" height="${canvas.height}" viewBox="0 0 ${canvas.width} ${canvas.height}">
  <!-- Generated by SPM PNG Studio (SPManchester Private Limited - www.spmanchester.com) -->
  <image width="100%" height="100%" href="data:image/png;base64,${btoa(b)}"/>
</svg>`;
  return new Blob([xml], { type: 'image/svg+xml' });
}

export async function canvasToBase64Blob(canvas) {
  const png = await canvasToBlob(canvas, 'image/png');
  const bytes = new Uint8Array(await png.arrayBuffer());
  let str = '';
  for (let i = 0; i < bytes.length; i += 32768) {
    str += String.fromCharCode(...bytes.subarray(i, i + 32768));
  }
  const payload = `data:image/png;base64,${btoa(str)}`;
  return new Blob([payload], { type: 'text/plain;charset=utf-8' });
}

export async function convertSingleImage({ file, targetFormat, scaleOrCustom = 1, customWidth = 1200, quality = 0.9 }) {
  const img = await decodeImage(file);
  const dims = calculateDimensions(img.naturalWidth || img.width, img.naturalHeight || img.height, scaleOrCustom, customWidth);
  const canvas = renderToCanvas(img, targetFormat, dims);

  let blob;
  const t = targetFormat.toUpperCase();

  if (['PNG', 'JPG', 'WEBP'].includes(t)) {
    blob = await canvasToBlob(canvas, MIME[t], quality);
  } else if (t === 'BMP') {
    blob = canvasToBmpBlob(canvas);
  } else if (t === 'ICO') {
    blob = await canvasToIcoBlob(canvas);
  } else if (t === 'SVG') {
    blob = await canvasToSvgBlob(canvas);
  } else if (t === 'PDF') {
    blob = await canvasToPdfBlob(canvas, quality);
  } else if (t === 'BASE64') {
    blob = await canvasToBase64Blob(canvas);
  } else {
    throw new Error(`Unsupported conversion format: ${targetFormat}`);
  }

  const baseName = (file.name || 'image').replace(/\.[^.]*$/i, '');
  const outputName = `${baseName}-converted.${EXT[t] || 'bin'}`;

  return {
    blob,
    name: outputName,
    width: canvas.width,
    height: canvas.height,
    format: t,
    size: blob.size
  };
}
